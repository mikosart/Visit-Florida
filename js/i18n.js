/* ================================================================
   i18n ENGINE
   ================================================================ */
(function(){
  var langMap = {
    'flags_lang-en-us.png': 'en',
    'flags_lang-es.png': 'es',
    'flags_lang-pt-br.png': 'pt'
  };

  function setLang(lang) {
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
      var key = el.getAttribute('data-i18n');
      if (translations[key] && translations[key][lang] != null) {
        el.innerHTML = translations[key][lang];
      }
    });
    // Swap localised images (data-i18n-img holds the EN base path)
    document.querySelectorAll('[data-i18n-img]').forEach(function(img) {
      var base = img.getAttribute('data-i18n-img'); // EN path
      if (lang === 'en') {
        img.setAttribute('src', base);
      } else {
        var parts = base.split('/');
        var filename = parts.pop();                         // e.g. cmg-01-campaign-mark-01.png
        var dir = parts.join('/');                           // folder without filename
        var name = filename.replace(/\.png$/i, '');
        var suffix = '-' + (lang === 'es' ? 'es' : 'pt');
        var langFolder = lang === 'es' ? 'es' : 'pt';
        img.setAttribute('src', dir + '/' + langFolder + '/' + name + suffix + '.png');
      }
    });
    // Swap localised hrefs (data-i18n-href holds translation key)
    document.querySelectorAll('[data-i18n-href]').forEach(function(el) {
      var key = el.getAttribute('data-i18n-href');
      if (translations[key] && translations[key][lang] != null) {
        el.setAttribute('href', translations[key][lang]);
      }
    });
    localStorage.setItem('vf-lang', lang);
    // Update html lang attribute for CSS selectors
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;
    // Highlight active flag
    document.querySelectorAll('.vf-flag').forEach(function(flag) {
      var img = flag.querySelector('img');
      if (!img) return;
      var src = img.getAttribute('src');
      var flagLang = Object.keys(langMap).find(function(k) { return src.indexOf(k) !== -1; });
      flag.classList.toggle('vf-flag--active', flagLang ? langMap[flagLang] === lang : false);
    });
  }

  document.addEventListener('DOMContentLoaded', function() {
    // Bind flag clicks
    document.querySelectorAll('.vf-flag').forEach(function(flag) {
      flag.addEventListener('click', function(e) {
        e.preventDefault();
        var img = flag.querySelector('img');
        if (!img) return;
        var src = img.getAttribute('src');
        var flagLang = Object.keys(langMap).find(function(k) { return src.indexOf(k) !== -1; });
        if (flagLang) setLang(langMap[flagLang]);
      });
    });
    // Apply saved language
    var saved = localStorage.getItem('vf-lang');
    if (saved && saved !== 'en') setLang(saved);
    else {
      // Just highlight English flag
      setLang('en');
    }
  });
})();
